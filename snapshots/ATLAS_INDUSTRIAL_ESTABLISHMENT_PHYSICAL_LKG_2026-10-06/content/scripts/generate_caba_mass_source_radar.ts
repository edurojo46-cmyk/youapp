function generateRadar() {
  console.log('================================================================');
  console.log('ATLAS PEOPLE — CABA MASS SOURCE RADAR V1');
  console.log('================================================================\n');

  // Register and compute score for each
  const scoredSources: (RegisteredSource & { score: number })[] = [];

  for (const c of cabaMassRadarCandidates) {
    const fullSource = c as RegisteredSource;
    const score = SourceCapabilityRegistry.calculateSourceAcquisitionScore(fullSource);
    fullSource.source_acquisition_score = score;
    scoredSources.push({ ...fullSource, score });
  }

  // Sort by score DESC
  scoredSources.sort((a, b) => b.score - a.score);

  // Assign Priority (1 to N)
  scoredSources.forEach((s, idx) => {
    (s as any).priority = idx + 1;
  });

  return scoredSources;
}

