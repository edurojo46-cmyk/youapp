import * as dotenv from 'dotenv';
dotenv.config({ path: '.env.local' });
dotenv.config({ path: '.env' });
import { createClient } from '@supabase/supabase-js';
import * as fs from 'fs';

const url = process.env.VITE_SUPABASE_URL || '';
const serviceKey = process.env.SUPABASE_SECRET_KEY || '';
const client = createClient(url, serviceKey); 

async function main() {
  console.log('--- ATLAS PERSON PROVENANCE BACKFILL & SNAPSHOT ---');

  let allPeople = [];
  let from = 0;
  const pageSize = 1000;
  
  while (true) {
    const { data, error } = await client.from('atlas_people')
      .select('person_id, tenant_id, full_name, created_at, origin_type')
      .range(from, from + pageSize - 1);
    
    if (error) throw error;
    if (!data || data.length === 0) break;
    
    allPeople.push(...data);
    from += pageSize;
    if (data.length < pageSize) break;
  }

  const people = allPeople;
  console.log(`Loaded ${people?.length || 0} rows.`);
  if (!people || people.length === 0) return;

  const tenantProfiles: Record<string, { total: number, hasGomez: boolean, hasRossi: boolean, allTestNames: boolean }> = {};
  
  for (const p of people) {
    if (!tenantProfiles[p.tenant_id]) {
      tenantProfiles[p.tenant_id] = { total: 0, hasGomez: false, hasRossi: false, allTestNames: true };
    }
    tenantProfiles[p.tenant_id].total++;
    if (p.full_name?.includes('Carlos Gomez')) tenantProfiles[p.tenant_id].hasGomez = true;
    if (p.full_name?.includes('Valeria Rossi')) tenantProfiles[p.tenant_id].hasRossi = true;
    if (!p.full_name?.toLowerCase().includes('test')) tenantProfiles[p.tenant_id].allTestNames = false;
  }

  const SYSTEM_TENANT = '00000000-0000-0000-0000-000000000000';
  const snapshotRows = [];
  const testIdsToUpdate: string[] = [];

  let deterministicCount = 0;
  let unknownCount = 0;

  for (const p of people) {
    let proposed = 'UNKNOWN';
    let reason = 'Insufficient evidence';

    if (p.tenant_id === SYSTEM_TENANT && tenantProfiles[p.tenant_id].allTestNames) {
      proposed = 'TEST';
      reason = 'System tenant consisting exclusively of Test fixtures';
    } else if (tenantProfiles[p.tenant_id].hasGomez && tenantProfiles[p.tenant_id].hasRossi) {
      proposed = 'TEST';
      reason = 'Tenant explicitly generated by integration/benchmark suites containing fixture signatures';
    }

    // Only update if it wasn't already updated in previous runs
    if (proposed === 'TEST') {
      if (p.origin_type !== 'TEST') testIdsToUpdate.push(p.person_id);
      deterministicCount++;
    } else {
      unknownCount++;
    }

    snapshotRows.push({
      person_id: p.person_id,
      tenant_id: p.tenant_id,
      full_name: p.full_name,
      created_at: p.created_at,
      current_origin: p.origin_type,
      proposed_origin: proposed,
      classification_reason: reason
    });
  }

  const snapshotData = JSON.stringify(snapshotRows, null, 2);
  fs.writeFileSync('atlas_people_snapshot_full.json', snapshotData);
  console.log(`\nSnapshot saved to atlas_people_snapshot_full.json.`);
  console.log(`DETERMINISTIC_TEST = ${deterministicCount}`);
  console.log(`UNKNOWN = ${unknownCount}`);
  console.log(`SUM = ${deterministicCount + unknownCount}`);

  console.log('\\nExecuting backfill for DETERMINISTIC_TEST rows...');
  if (testIdsToUpdate.length > 0) {
    const chunkSize = 500;
    for (let i = 0; i < testIdsToUpdate.length; i += chunkSize) {
      const chunk = testIdsToUpdate.slice(i, i + chunkSize);
      const { error: updateErr } = await client.from('atlas_people')
        .update({ origin_type: 'TEST' })
        .in('person_id', chunk);
      
      if (updateErr) {
        console.error('Update chunk error:', updateErr);
      } else {
        console.log(`Updated chunk ${i} to ${i + chunk.length}`);
      }
    }
  } else {
      console.log('No new rows to update.');
  }

  console.log('\nBACKFILL_COMPLETE = YES');
}

main().catch(console.error);
